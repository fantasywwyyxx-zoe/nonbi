import json, re, subprocess, sys, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
fails = []
def ok(cond, msg):
    print(("PASS " if cond else "FAIL ") + msg)
    if not cond: fails.append(msg)

html = open(ROOT + "/index.html").read()
ok("assets/bot-hi.webp" in html, "index references bot-hi.webp")
ok("assets/logo.png" in html, "index references logo.png")
ok("getElementById('stage')" not in html and "spawnBurst" in html, "foam bursts mount on #ph (no #stage exists)")
ok("orderNear" in html and "setSort" in html and "近い順" in html and "おすすめ順" in html, "near-sort toggle present")
for a in ("bot-hi.webp", "hana.jpg", "kaze.jpg", "elm.jpg", "logo.png"):
    ok(os.path.exists(ROOT + "/assets/" + a), "asset exists: " + a)
    ok(os.path.getsize(ROOT + "/assets/" + a) > 3000, "asset non-trivial: " + a)
m = re.search(r"<script>\nvar MODE(.*?)</script>", html, re.S)
ok(m is not None, "main script found")
if m:
    open("/tmp/_nonbi_check.js", "w").write("var MODE" + m.group(1))
    r = subprocess.run(["node", "--check", "/tmp/_nonbi_check.js"], capture_output=True, text=True)
    ok(r.returncode == 0, "JS syntax valid" + ("" if r.returncode == 0 else ": " + r.stderr[:200]))
S = json.load(open(ROOT + "/data/ikebukuro.json"))
ok(len(S) == 144, "data has 144 shops (got %d)" % len(S))
ok(all(s["n"] and s["a"] for s in S), "every shop has name + address")
HIRA = set("はがをにへともでしてくなりますやよかねぞわのんた")
KATA = set(chr(c) for c in range(0x30A1, 0x30F7))
def is_zh(t):
    if not t or len(t) < 6: return False
    if any(c in HIRA for c in t): return False
    if any(c in KATA for c in t): return False
    return any('一' <= c <= '鿿' for c in t)
ok(not any(is_zh(s["w"]) or is_zh(s["s"]) for s in S), "all user-visible text is Japanese (no Chinese fields)")
ok(sum(1 for s in S if s["gs"] and s["ts"]) == 139, "dual-score shops == 139")
ok(sum(1 for s in S if s.get("ph")) >= 103, "google-photo shops >= 103")
ok(sum(1 for s in S if s.get("pid")) == 141, "place ids == 141")
ok(sum(1 for s in S if s["ts"]) == 142, "tabelog-scored == 142")
ok(len(set(s["id"] for s in S)) == 144, "ids unique")
SJ = json.load(open(ROOT + "/data/shinjuku.json"))
ok(len(SJ) == 190, "shinjuku has 190 shops (got %d)" % len(SJ))
ok(all(s["n"] for s in SJ), "shinjuku every shop has a name")
ok(sum(1 for s in SJ if s["a"]) >= 188, "shinjuku addresses present (>=188)")
ok(not any(is_zh(s["w"]) or is_zh(s["s"]) for s in SJ), "shinjuku text is Japanese")
ok(sum(1 for s in SJ if s["ts"]) == 151, "shinjuku tabelog-scored == 151")
ok(sum(1 for s in SJ if s["gs"]) == 176, "shinjuku google-scored == 176")
ok(sum(1 for s in SJ if s["gs"] and s["ts"]) == 141, "shinjuku dual-scored == 141")
ok(sum(1 for s in SJ if s.get("ph")) == 164, "shinjuku photo shops == 164")
ok(sum(1 for s in SJ if s.get("pid")) == 175, "shinjuku place ids == 175")
ok(all(not s["t"] or all(c.isdigit() or c == "-" for c in s["t"]) for s in S + SJ), "tel fields are clean single numbers")
ok(len(set(s["id"] for s in SJ)) == 190, "shinjuku ids unique")
ok(os.path.exists(ROOT + "/version.txt"), "version.txt present")
ok("user-scalable=no" in html, "viewport locks double-tap zoom")
ok("-webkit-touch-callout" in html and "touch-action:manipulation" in html, "long-press callout off + touch-action set")
ok("position:sticky" in html, "detail action row is sticky")
print("RESULT:", "ALL PASS" if not fails else "%d FAILURES" % len(fails))
sys.exit(1 if fails else 0)
